const cdp = require('./lib/cdp.cjs')
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
;(async () => {
  const b = await cdp.launch({ headless: true })
  const p = await b.newPage()
  await p.goto('http://127.0.0.1:5180', { waitUntil: 'load', timeoutMs: 60000 })
  await sleep(4000)
  await p.evaluate(() => document.querySelector('[data-testid="nav-files"]')?.click())
  await sleep(3000)
  await p.evaluate(() => document.querySelector('[data-testid="nav-child-cat-video"]')?.click())
  await sleep(4000)
  const n = await p.evaluate(() => document.querySelectorAll('[data-testid="media-card"]').length)
  console.log('media-card count =', n)
  await p.screenshot('verify_shots/bug413-card.png')
  console.log('shot written')
  await b.close()
})().catch((e) => { console.error(e.message); process.exit(1) })
