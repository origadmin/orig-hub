/**
 * 渲染层剧名标记（BUG-251）。
 *
 * 背景：剧集标题是**自由文本** —— 用户/来源可能已经自带书名号。实测库里
 * 约 45.7%（16/35）的剧集标题**本就含 `《`**（如 `《小镇上的熟母露出俱乐部》`、
 * `#ai短剧 #Ai成人短剧 《苏老师的裸贷人生》`、`😀😀😀😀😀😀😀😀 #《存在感零》`）。
 * 渲染层若再无脑套一层 `《{title}》`，近半数剧集会显示成 `《《…》》`。
 *
 * 规则只有一条 —— **已含 `《` 就原样返回，否则包一层**：
 *   - 不做括号「增删」平衡校正；
 *   - **不剥内部书名号**（那会侵入标题内容：`#ai短剧 《X》` 里的 `《X》` 是标题自身的一部分）。
 *
 * 本函数是「把剧名放进一句会包裹它的文案里」的**唯一入口**：凡是原本写死
 * `《{title}》` / `` 《${title}》 `` 的位置，一律改用它，避免双书名号。
 *
 * 注意：**剧集卡片正面**（`SeriesCard.tsx` 直接输出 `series.title`）**不适用**本函数 ——
 * 那里本就不包裹，加了反而会改变既有卡面外观。
 *
 * @param title 原始剧名（可为空/null；调用方通常传入对象字段）
 * @returns 已带单层书名号的剧名；空串原样返回 `''`
 */
export function seriesLabel(title: string): string {
  const t = (title ?? '').trim()
  if (t === '') return t
  return t.includes('《') ? t : `《${t}》`
}
